// Turns integrations/google-form/setup.template.gs into a JS string constant the app can show to the user.
// Run after editing the .gs file:  npm run gen
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(resolve(root, 'integrations/google-form/setup.template.gs'), 'utf8');
const out = resolve(root, 'src/generated/form-script.js');
mkdirSync(dirname(out), { recursive: true });
// "</" is escaped so the string stays safe when inlined into a <script> tag by the single-file build.
const literal = JSON.stringify(src).replace(/<\//g, '<\\/');
writeFileSync(out, `/* GENERATED by scripts/gen-form-script.mjs from integrations/google-form/setup.template.gs. Do not edit. */\nconst FORM_SCRIPT=${literal};\n`);
console.log('wrote src/generated/form-script.js');
