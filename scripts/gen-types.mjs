// Writes src/types/database.d.ts: one TypeScript type per table, read from the real database, so the shape of every row is written down once.
//   npm run types        needs DATABASE_URL in .env. Run it after a migration and commit the result.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { connect } from './db.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const TS = { text: 'string', varchar: 'string', bpchar: 'string', uuid: 'string', citext: 'string', date: 'string', time: 'string', timestamptz: 'string', timestamp: 'string',
  int2: 'number', int4: 'number', int8: 'number', numeric: 'number', float4: 'number', float8: 'number', bool: 'boolean', jsonb: 'Json', json: 'Json' };
const pascal = (s) => s.replace(/(^|_)(\w)/g, (_, __, c) => c.toUpperCase());

export function typeOf(udt, enumValues) {
  if (udt.startsWith('_')) return `${typeOf(udt.slice(1), enumValues)}[]`;
  if (enumValues[udt]) return enumValues[udt].map((v) => `'${v}'`).join(' | ');
  return TS[udt] || 'unknown';
}

export function render(tables, enums) {
  const out = ['/* GENERATED by scripts/gen-types.mjs from the database. Do not edit; run `npm run types` after a migration. */', '',
    'export type Json = string | number | boolean | null | { [key: string]: Json } | Json[];', ''];
  for (const [name, cols] of Object.entries(tables)) {
    out.push(`export interface ${pascal(name)} {`);
    for (const c of cols) out.push(`  ${c.name}: ${typeOf(c.udt, enums)}${c.nullable ? ' | null' : ''};`);
    out.push('}', '');
  }
  out.push('export interface Tables {', ...Object.keys(tables).map((t) => `  ${t}: ${pascal(t)};`), '}', '');
  return out.join('\n');
}

async function main() {
  const c = connect();
  await c.connect();
  const cols = (await c.query(`select table_name, column_name, udt_name, is_nullable from information_schema.columns
    where table_schema = 'public' and table_name in (select table_name from information_schema.tables where table_schema = 'public' and table_type = 'BASE TABLE')
    order by table_name, ordinal_position`)).rows;
  const en = (await c.query(`select t.typname, array_agg(e.enumlabel::text order by e.enumsortorder) vals from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace where n.nspname = 'public' group by t.typname`)).rows;
  await c.end();
  const tables = {};
  for (const r of cols) (tables[r.table_name] ||= []).push({ name: r.column_name, udt: r.udt_name, nullable: r.is_nullable === 'YES' });
  const file = resolve(root, 'src/types/database.d.ts');
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, render(tables, Object.fromEntries(en.map((e) => [e.typname, e.vals]))));
  console.log(`src/types/database.d.ts  (${Object.keys(tables).length} tables)`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) main();
